const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
;(async () => {
 const browser = await chromium.launch(require('./smoke-launch.cjs')())
 const base=process.env.SMOKE_BASE_URL || 'http://127.0.0.1:5197', out=process.env.UX_QA_OUTPUT || '../oil-evidence/ux-fixes'
 fs.mkdirSync(out,{recursive:true})
 const results=[]
 for(const width of [390,820,1440]) {
  const context=await browser.newContext({viewport:{width,height:1000},serviceWorkers:'block'})
  const page=await context.newPage(), errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  const now=Date.parse('2026-10-25T15:00:00Z'), previous=Date.parse('2026-10-23T15:00:00Z')
  await page.clock.install({time:new Date(now)})
  let intradayFail=false
  const curve={compare:[{id:'hoje',date:'2026-10-23',label:'Hoje'}],curves:{'2026-10-23':[[21,12],[252,13],[504,13.2]]}}
  await context.route('**/*',route=>{
   const url=new URL(route.request().url()), name=url.pathname.split('/').pop()
   if(name==='intraday.json') return intradayFail ? route.abort() : route.fulfill({json:{generatedAt:previous,source:'Fixture UX',resolution:'5 min',series:Object.fromEntries(['USD','EUR','JPY','CNH'].map(c=>[c,{points:[[previous-300000,5],[previous,5.1]]}]))}})
   if(name==='curves.json')return route.fulfill({json:{generatedAt:now,br:curve,cc:curve,us:curve}})
   if(name==='macro.json')return route.fulfill({json:{generatedAt:now,cdi:[[previous,12]],selic:[[previous,12]],sofr:[[previous,4]],ptax:{},ptaxHist:{}}})
   if(url.hostname==='economia.awesomeapi.com.br')return route.fulfill({json:Object.fromEntries(['USDBRL','EURBRL','JPYBRL','USDCNH'].map(c=>[c,{bid:'5',ask:'5.01',high:'5.1',low:'4.9',pctChange:'1',timestamp:String(now/1000)}]))})
   if(url.origin===new URL(base).origin)return route.continue()
   return route.abort()
  })
  await page.goto(base+'/#resumo')
  await page.getByRole('button',{name:'Dólar americano: abrir gráfico',exact:true}).waitFor() // o botão de atualizar só ocupa espaço depois que as cotações carregam
  const sizes=await page.locator('.img-share,.refresh-mini,.help button:not(.pop-close)').evaluateAll(es=>es.map(e=>({label:e.getAttribute('aria-label'),w:e.getBoundingClientRect().width,h:e.getBoundingClientRect().height})))
  assert.ok(sizes.every(s=>s.w>=44 && s.h>=44))
  assert.match(await page.locator('.status.src').innerText(),/Câmbio.*25\/10\/2026.*Brasília/)
  await page.screenshot({path:`${out}/${width}-empty.png`,fullPage:true})
  assert.equal(await page.locator('.calendar-trigger,.resumo-chart').count(),0)
  await page.locator('.terminal-news').waitFor()
  await page.getByRole('button',{name:'Dólar americano: abrir gráfico',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'detalhes da moeda'})
  await dialog.waitFor()
  await dialog.locator('input[type=date]').first().fill('2026-10-23')
  await dialog.locator('svg[tabindex="0"]').waitFor()
  await dialog.locator('svg[tabindex="0"]').focus();await page.keyboard.press('End')
  assert.match(await dialog.locator('.chart-access-text[role="status"]').innerText(),/Cotação/)
  await page.keyboard.press('Escape')
  await dialog.waitFor({state:'hidden'})
  await page.screenshot({path:`${out}/${width}-previous.png`,fullPage:true})
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)
  assert.equal(overflow,false)
  await page.goto(base+'/#juros')
  await page.getByRole('heading',{name:'Juros',exact:true}).waitFor()
  await page.locator('.status.src').waitFor({state:'detached'})
  assert.equal(await page.locator('.status.src').count(),0)
  await page.goBack();await page.waitForURL('**/#resumo')
  await page.goForward();await page.waitForURL('**/#juros')
  intradayFail=true
  await page.reload();await page.goto(base+'/#resumo')
  await page.clock.fastForward(11*60000)
  await page.waitForTimeout(300)
  await page.getByRole('button',{name:'Dólar americano: abrir gráfico',exact:true}).click()
  const failDialog=page.getByRole('dialog',{name:'detalhes da moeda'});await failDialog.waitFor()
  await failDialog.getByText(/intraday indisponível/).first().waitFor({timeout:15000}) // o carregamento é assíncrono: espera o estado de erro em vez de ler o texto no instante da abertura
  assert.match(await failDialog.innerText(),/intraday indisponível/)
  await page.keyboard.press('Escape');await failDialog.waitFor({state:'hidden'})
  await page.screenshot({path:`${out}/${width}-failure.png`,fullPage:true})
  assert.deepEqual(errors,[])
  results.push({width,passed:true,overflow,errors,sizes,checks:['money input','inline feedback','keyboard','empty vs error','previous actual samples','timestamp scope','44px controls','modal/Escape','BackForward']})
  await context.close()
 }
 await browser.close()
 fs.writeFileSync(out+'/results.json',JSON.stringify(results,null,2));console.log(JSON.stringify(results,null,2))
})().catch(e=>{console.error(e);process.exit(1)})
