// Runs inside the existing calculator smoke, using synthetic values only.
const assert = require('node:assert/strict')
const path = require('node:path')
const normalize = text => text.replace(/\s+/g, ' ').trim()

module.exports = async function checkAlongamento(page, section, directory, width, assertWorkspace, settleLayout) {
  await section.getByRole('button', { name: 'Comparar com parcelado', exact: true }).click()
  const component = section.locator('.alongamento')
  await component.waitFor({ state: 'visible' })
  assert.equal(await component.locator('.along-results').count(), 0)
  for (const [key, value] of Object.entries({ balance: '300000', cgRate: '3', amount: '300000', loanRate: '1,5', n: '36', start: '2026-11-06' })) await component.locator(`#along-${key}`).fill(value)
  await component.locator('.along-results').waitFor()
  assert.match(normalize(await component.locator('.along-cash-summary').innerText()), /10\.845,72/)
  const final = component.getByRole('row', { name: /Dívida restante ao final/ })
  assert.match(normalize(await final.innerText()), /300\.000,00.*0,00/)
  assert.equal(await component.locator('input[id*=iof]').count(), 0)
  await component.locator('#along-cashAvailable').fill('0')
  assert.match(await component.locator('.along-alert').innerText(), /risco de reutilizar o limite/)
  await component.locator('#along-cashAvailable').fill('15000')
  assert.equal(await component.locator('.along-alert').count(), 0)
  const help = component.getByRole('button', { name: 'Ajuda: Giro parcelado', exact: true })
  await help.click()
  const dialog = page.getByRole('dialog', { name: 'Giro parcelado', exact: true })
  await dialog.waitFor()
  await page.keyboard.press('Escape')
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(await help.evaluate(node => node === document.activeElement), true)
  await settleLayout(page)
  await assertWorkspace(page, section, `alongamento preenchido ${width}`)
  await page.screenshot({ path: path.join(directory, 'alongamento-filled.png'), fullPage: true })

  await component.locator('#along-amount').fill('400000')
  assert.equal(await component.locator('.along-results').count(), 0)
  await component.locator('#along-amount').fill('200000')
  await component.locator('.along-results').waitFor()
  assert.match(normalize(await final.innerText()), /300\.000,00.*100\.000,00/)
  await component.locator('#along-system').selectOption('sac')
  await component.locator('#along-graceMonths').fill('2')
  await component.getByText('Evolução mensal dos pagamentos e da dívida', { exact: true }).click()
  assert.match(await component.locator('.along-schedule tbody tr').first().innerText(), /Carência/)

  await component.locator('.along-ncg > summary').click()
  for (const [key, value] of Object.entries({ receivables: '100000', inventory: '50000', payables: '80000' })) await component.locator(`#ncg-${key}`).fill(value)
  assert.match(normalize(await component.locator('.along-ncg-result').innerText()), /70\.000,00/)
  await component.getByRole('button', { name: 'Estimar pelos prazos', exact: true }).click()
  for (const [key, value] of Object.entries({ sales: '300000', pmr: '60', cost: '180000', pme: '45', purchases: '150000', pmp: '30' })) await component.locator(`#ncg-${key}`).fill(value)
  assert.match(normalize(await component.locator('.along-ncg-result').innerText()), /720\.000,00.*75 dias/)
  await component.locator('#along-loanRate').fill('')
  assert.equal(await component.locator('.along-results').count(), 0)
  assert.equal(await component.locator('.along-ncg-result').count(), 1)
  await component.locator('#along-loanRate').fill('1,5')
  await component.locator('.along-results').waitFor()
  await settleLayout(page)
  await assertWorkspace(page, section, `alongamento NCG ${width}`)
  await page.screenshot({ path: path.join(directory, 'alongamento-ncg.png'), fullPage: true })
  await section.getByRole('button', { name: 'Lançamentos por dia', exact: true }).click()
  await section.getByRole('button', { name: 'Comparar com parcelado', exact: true }).click()
  assert.equal(await component.locator('#along-amount').inputValue(), '200.000,00')
  console.log(`PASS alongamento, caixa, IOF, NCG e retorno ${width}`)
}
