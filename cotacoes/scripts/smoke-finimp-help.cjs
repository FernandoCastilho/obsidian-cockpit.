const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs')

// Conversor da aba Mercado: dados sintéticos, sem depender da cotação publicada.
async function smokeConverter(browser, width, base, out) {
  const p = await browser.newPage({ viewport: { width, height: 900 }, hasTouch: true, serviceWorkers: 'block' })
  const errors = [], now = Date.now()
  p.on('pageerror', error => errors.push(error.message))
  const quote = bid => ({ bid, ask: bid * 1.0001, high: bid * 1.01, low: bid * 0.99, pctChange: 0, timestamp: Math.floor(now / 1000) })
  const quotes = { USDBRL: quote(5), EURBRL: quote(5.586), JPYBRL: quote(0.035), USDCNH: quote(7.1), EURUSD: quote(1.1172) }
  await p.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.pathname.endsWith('/quotes.json')) return route.fulfill({ json: { generatedAt: now, quotes } })
    if (url.hostname === 'economia.awesomeapi.com.br') return route.fulfill({ json: quotes })
    if (url.origin === new URL(base).origin) return route.continue()
    return route.abort()
  })
  try {
    await p.goto(base + '/#resumo')
    const trigger = p.getByRole('button', { name: 'Paridade para a Finimp', exact: true })
    await trigger.waitFor()
    const market = p.locator('.kpi-cell').filter({ has: trigger }).locator('.kpi-value')
    assert.equal(await market.innerText(), '1,1172')
    assert.equal(await trigger.getAttribute('aria-haspopup'), 'dialog')
    await trigger.focus()
    assert.equal(await p.getByRole('dialog', { name: 'Paridade para a Finimp', exact: true }).count(), 0, 'foco sozinho não abre formulário')
    await p.keyboard.press('Enter')
    const dialog = p.getByRole('dialog', { name: 'Paridade para a Finimp', exact: true })
    await dialog.waitFor()
    assert.equal(await dialog.evaluate(el => el.matches(':modal')), true)
    assert.equal(await p.getByRole('tooltip').filter({ has: p.locator('input') }).count(), 0)
    assert.equal(await trigger.getAttribute('aria-controls'), await dialog.getAttribute('id'))
    const eur = dialog.getByRole('radio', { name: 'Pagamento em EUR, financiamento em USD', exact: true })
    const usd = dialog.getByRole('radio', { name: 'Pagamento em USD, financiamento em EUR', exact: true })
    assert.equal(await eur.evaluate(el => el.tagName), 'INPUT')
    assert.equal(await eur.evaluate(el => el === document.activeElement), true, 'Enter move foco ao rádio selecionado')
    await p.keyboard.press('ArrowRight'); assert.equal(await usd.isChecked(), true)
    await p.keyboard.press('ArrowRight'); assert.equal(await eur.isChecked(), true, 'seta dá a volta no grupo')
    await p.keyboard.press('ArrowLeft'); assert.equal(await usd.isChecked(), true)
    await p.keyboard.press('ArrowUp'); assert.equal(await eur.isChecked(), true)
    await p.keyboard.press('ArrowDown'); assert.equal(await usd.isChecked(), true)
    await p.keyboard.press('ArrowLeft'); assert.equal(await eur.isChecked(), true)
    await p.keyboard.press('Tab')
    let amount = dialog.getByRole('textbox', { name: 'Valor do pagamento (EUR)', exact: true })
    assert.equal(await amount.evaluate(el => el === document.activeElement), true, 'Tab entra no campo, sem ir ao IPCA')
    await amount.fill('100000')
    assert.match(await dialog.locator('.fin-result').innerText(), /113\.720,00/)
    assert.match(await dialog.innerText(), /\(\+0,02\).*1,1372/)
    assert.match(await dialog.innerText(), /\(−0,02\).*1,0972/)
    await p.keyboard.press('Shift+Tab')
    await p.keyboard.press('ArrowRight')
    assert.equal(await usd.isChecked(), true)
    assert.match(await dialog.locator('.fin-result').innerText(), /91\.141,09/)
    await p.keyboard.press('Tab')
    amount = dialog.getByRole('textbox', { name: 'Valor do pagamento (USD)', exact: true })
    assert.equal(await amount.evaluate(el => el === document.activeElement), true)
    await amount.fill('-1')
    assert.equal(await amount.getAttribute('aria-invalid'), 'true')
    assert.doesNotMatch(await dialog.locator('.fin-result').innerText(), /91\.141,09|113\.720,00/)
    await amount.fill('100000')
    const close = dialog.getByRole('button', { name: 'Fechar conversor', exact: true })
    await close.focus(); await p.keyboard.press('Tab')
    assert.equal(await usd.evaluate(el => el === document.activeElement), true, 'Tab final volta ao rádio marcado')
    await p.keyboard.press('Shift+Tab')
    assert.equal(await close.evaluate(el => el === document.activeElement), true)
    assert.equal(await trigger.evaluate(el => { el.focus(); return el === document.activeElement }), false, 'fundo inerte')
    const box = await dialog.boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= width + 1 && box.y >= 0 && box.y + box.height <= 900)
    assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await p.screenshot({ path: `${out}/converter-${width}.png` })
    await amount.focus(); await p.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' })
    assert.equal(await trigger.evaluate(el => el === document.activeElement), true, 'Escape do campo restaura foco')
    assert.equal(await trigger.getAttribute('aria-expanded'), 'false')
    for (const method of ['button', 'outside', 'escape']) {
      await p.keyboard.press('Space'); await dialog.waitFor()
      assert.equal(await usd.evaluate(el => el === document.activeElement), true, 'reabertura preserva seleção e foco')
      assert.match(await dialog.locator('.fin-result').innerText(), /91\.141,09/)
      if (method === 'button') await close.click()
      else if (method === 'outside') await p.mouse.click(2, 2)
      else await p.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
      assert.equal(await trigger.evaluate(el => el === document.activeElement), true, `${method} restaura foco`)
      assert.equal(await market.innerText(), '1,1172', 'cotação de mercado não recebe margem')
    }
    // Fechamento repetido não reabre o diálogo nem perde o foco.
    await p.keyboard.press('Escape')
    assert.equal(await trigger.evaluate(el => el === document.activeElement), true)
    assert.deepEqual(errors, [])
    console.log(`PASS conversor FINIMP: dialog, rádio nativo, Tab, Escape, reabertura, clique externo e margem 0,02 ${width}`)
  } finally { await p.close() }
}

