const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs')
;(async()=>{
  const browser=await chromium.launch(require('./smoke-launch.cjs')()),base=process.env.SMOKE_BASE_URL||'http://127.0.0.1:8774',out=process.env.FINIMP_HELP_QA_OUTPUT||'workspace-qa/finimp-help'
  fs.mkdirSync(out,{recursive:true})
  try{for(const width of [390,820,1280]){
    const p=await browser.newPage({viewport:{width,height:900},hasTouch:true,serviceWorkers:'block'}),errors=[]
    p.on('pageerror',error=>errors.push(error.message))
    await p.goto(base+'/#calculadora/finimp')
    const section=p.locator('section.fi');await section.waitFor()
    assert.equal(await p.getByRole('dialog').count(),0)
    assert.doesNotMatch(await section.innerText(),/A moeda apenas identifica|Flat cobrado|As mesmas condições|Calcula a taxa anual/)
    assert.equal(await section.locator('.fi-tac-status').innerText(),'TAC excluída.')
    for(const title of ['Moeda','Prazo e base de cálculo','Flat · Instituição 1','Flat · Instituição 2','TAC','Custo total · Instituição 1','Atingir meta']){
      const button=p.getByRole('button',{name:'Ajuda: '+title,exact:true})
      const buttonBox=await button.boundingBox();assert.ok(buttonBox.width>=44&&buttonBox.height>=44,'área de ajuda com pelo menos 44px')
      if(width!==390){
        await button.hover()
        const preview=p.getByRole('tooltip');await preview.waitFor()
        assert.ok((await preview.innerText()).includes(title))
        const previewBox=await preview.boundingBox();assert.ok(previewBox.x>=0&&previewBox.x+previewBox.width<=width+1)
        await p.keyboard.press('Escape');await preview.waitFor({state:'hidden'})
      }
      if(width===390)await button.tap();else await button.click()
      const dialog=p.getByRole('dialog',{name:title,exact:true});await dialog.waitFor()
      assert.equal(await dialog.evaluate(el=>el.matches(':modal')),true)
      assert.equal(await dialog.evaluate(el=>el.contains(document.activeElement)),true)
      const box=await dialog.boundingBox();assert.ok(box.x>=0&&box.x+box.width<=width+1&&box.y>=0&&box.y+box.height<=900)
      for(const key of ['Tab','Tab','Shift+Tab']){
        await p.keyboard.press(key)
        assert.equal(await dialog.evaluate(el=>el===document.activeElement||el.contains(document.activeElement)),true,'foco contido na ajuda modal')
      }
      await p.screenshot({path:`${out}/${title.replace(/[^\p{L}\d]/gu,'-')}-${width}.png`})
      await p.keyboard.press('Escape');await dialog.waitFor({state:'hidden'})
      assert.equal(await button.evaluate(el=>el===document.activeElement),true,'Escape devolve foco ao ?')
      assert.equal(await button.getAttribute('aria-expanded'),'false')
    }
    const moeda=p.getByRole('button',{name:'Ajuda: Moeda',exact:true})
    await moeda.focus();await p.keyboard.press('Enter');await p.getByRole('dialog',{name:'Moeda',exact:true}).getByRole('button',{name:'Fechar ajuda'}).click()
    assert.equal(await moeda.evaluate(el=>el===document.activeElement),true)
    await p.locator('#fi-principal').fill('100000');await p.locator('#fi-a-rate').fill('6');await p.locator('#fi-b-rate').fill('8')
    await p.locator('#fi-a-flat').fill('1,5');await p.locator('#fi-b-flat').fill('2')
    const row=section.locator('tbody tr').nth(5)
    assert.match(await row.locator('td').nth(1).innerText(),/1.500,00/)
    assert.match(await row.locator('td').nth(5).innerText(),/2.000,00/)
    assert.match(await row.locator('.fi-cost').nth(0).innerText(),/4.500,00/)
    assert.match(await row.locator('.fi-cost').nth(1).innerText(),/6.000,00/)
    await section.getByRole('checkbox').check();assert.equal(await section.locator('.fi-tac-status').innerText(),'TAC incluída.')
    await p.getByRole('button',{name:'Ajuda: TAC',exact:true}).click();assert.match(await p.getByRole('dialog',{name:'TAC',exact:true}).innerText(),/à vista e sem financiamento/)
    assert.match(await p.getByRole('dialog',{name:'TAC',exact:true}).innerText(),/sempre informada em reais/)
    await p.getByRole('dialog',{name:'TAC',exact:true}).getByRole('button',{name:'Fechar ajuda'}).click()
    await p.locator('#fi-a-tac').fill('1000');await p.locator('#fi-b-tac').fill('1000')
    await p.getByRole('button',{name:'Ajuda: Câmbio da TAC · USD',exact:true}).click()
    assert.match(await p.getByRole('dialog',{name:'Câmbio da TAC · USD',exact:true}).innerText(),/TAC em R\$ ÷ câmbio/)
    await p.keyboard.press('Escape')
    await p.locator('#fi-tac-fx').fill('5')
    assert.match(await row.locator('.fi-cost').first().innerText(),/4\.700,00/)
    assert.match(await row.locator('.fi-cost').nth(1).innerText(),/6\.200,00/)
    assert.equal(await p.locator('#fi-a-flat').inputValue(),'1,50')
    assert.equal(await p.locator('#fi-b-flat').inputValue(),'2,00')
    assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    assert.deepEqual(errors,[])
    await p.screenshot({path:`${out}/page-${width}.png`,fullPage:true})
    await p.close();console.log(`PASS ajudas e flat editável nas duas instituições ${width}`)
  }}finally{await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)})
