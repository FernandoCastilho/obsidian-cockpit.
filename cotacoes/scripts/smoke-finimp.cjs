const { chromium } = require('playwright'), assert = require('node:assert/strict'), fs = require('node:fs')
;(async () => {
  const browser = await chromium.launch(require('./smoke-launch.cjs')())
  const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:5221'
  const out = process.env.FINIMP_QA_OUTPUT || 'workspace-qa/finimp'
  fs.mkdirSync(out, { recursive: true })
  try {
    for (const width of [390, 820, 1280]) {
      const p = await browser.newPage({ viewport: { width, height: 1000 }, hasTouch: true, serviceWorkers: 'block' }), errors = []
      p.on('pageerror', e => errors.push(e.message))
      await p.goto(base + '/#calculadora')
      await p.getByRole('button', { name: 'FINIMP: abrir calculadora' }).click()
      await p.waitForURL('**/#calculadora/finimp')
      const section = p.locator('section.fi')
      await section.waitFor()
      assert.deepEqual(await section.locator('.fi-bank legend').allTextContents(), ['Instituição 1', 'Instituição 2'])
      assert.deepEqual(await section.locator('thead th[scope=colgroup]').allTextContents(), ['Instituição 1', 'Instituição 2', 'Comparação'])
      assert.equal(await section.getByRole('option', {name:'Igualar custo da Instituição 1'}).count(),1)
      assert.doesNotMatch(await section.innerText(), /concorrente|Itaú/i)
      await p.locator('#fi-principal').fill('100000')
      await p.locator('#fi-a-rate').fill('6')
      await p.locator('#fi-a-flat').fill('1')
      await p.locator('#fi-b-rate').fill('8')
      await p.locator('#fi-b-flat').fill('0,5')
      await p.locator('#fi-b-rate').fill('')
      assert.match(await section.locator('.fi-goal').innerText(), /7,00% a.a./)
      await p.locator('#fi-b-rate').fill('8')
      const rows = section.locator('tbody tr')
      assert.equal(await rows.count(), 12)
      for (const [i, expected] of [[0, ['1.500,00', '1.166,67']], [1, ['2.000,00', '1.833,33']], [2, ['2.500,00', '2.500,00']], [3, ['3.000,00', '3.166,67']], [4, ['3.500,00', '3.833,33']], [5, ['4.000,00', '4.500,00']], [6, ['4.500,00', '5.166,67']], [7, ['5.000,00', '5.833,33']], [8, ['5.500,00', '6.500,00']], [9, ['6.000,00', '7.166,67']], [10, ['6.500,00', '7.833,33']], [11, ['7.000,00', '8.500,00']]]) {
        for (let col = 0; col < 2; col++) assert.ok((await rows.nth(i).locator('td strong').nth(col).innerText()).includes(expected[col]))
      }
      assert.doesNotMatch(await section.innerText(), /Instituição 2 com (menor|maior) custo|Custos iguais/)
      assert.match(await rows.first().locator('td').nth(3).innerText(), /1,50%/)
      assert.match(await rows.first().locator('td').nth(7).innerText(), /1,17%/)
      assert.ok((await rows.nth(5).getByRole('button').boundingBox()).height >= 44, 'seleção do prazo tem área acessível')
      const assertWholeValues = async () => {
        const values = await rows.locator('td:not([colspan])').evaluateAll(cells => cells.map(cell => {
          const range = document.createRange()
          range.selectNodeContents(cell)
          const text = range.getBoundingClientRect(), box = cell.getBoundingClientRect(), style = getComputedStyle(cell)
          return { nowrap: style.whiteSpace === 'nowrap', fits: text.left >= box.left - 1 && text.right <= box.right + 1, oneLine: text.height <= parseFloat(style.lineHeight) + 1 }
        }))
        assert.ok(values.every(value => value.nowrap && value.fits && value.oneLine), 'valores completos em uma linha, dentro de cada célula')
      }
      await assertWholeValues()
      const valuesBeforeSelection = await rows.allTextContents()
      await rows.nth(3).locator('td').first().click()
      assert.equal(await rows.nth(3).getAttribute('class'), 'fi-row-selected')
      assert.equal(await rows.nth(3).getByRole('button').getAttribute('aria-pressed'), 'true')
      const enterButton = rows.nth(5).getByRole('button', { name: 'Selecionar prazo de 180 dias' })
      await enterButton.focus()
      await p.keyboard.press('Enter')
      assert.equal(await enterButton.getAttribute('aria-pressed'), 'true')
      const spaceButton = rows.nth(7).getByRole('button', { name: 'Selecionar prazo de 240 dias' })
      await spaceButton.focus()
      await p.keyboard.press('Space')
      assert.equal(await spaceButton.getAttribute('aria-pressed'), 'true')
      assert.equal(await rows.locator('button[aria-pressed=true]').count(), 1)
      assert.deepEqual(await rows.allTextContents(), valuesBeforeSelection, 'selecionar não altera resultados')
      const colors = await rows.nth(7).locator('th, td').evaluateAll(cells => cells.map(cell => getComputedStyle(cell).backgroundColor))
      assert.equal(new Set(colors).size, 1, 'prazo fixo e todas as células recebem o mesmo destaque')
      assert.match(await section.locator('.fi-goal').innerText(), /7,00% a.a./)
      await section.getByRole('button', { name: 'Aplicar taxa à Instituição 2' }).click()
      assert.match(await rows.nth(5).locator('.fi-difference').innerText(), /0,00/)
      assert.equal(await rows.nth(5).locator('.fi-delta').innerText(), '0,00 p.p.')
      assert.equal(await p.locator('#fi-b-rate').inputValue(), '7,00')
      await p.locator('#fi-goal-mode').selectOption('target')
      await p.locator('#fi-target').fill('2000')
      assert.match(await section.locator('.fi-goal').innerText(), /3,00% a.a./)
      await p.locator('#fi-target').fill('100')
      assert.match(await section.locator('.fi-goal').innerText(), /Não há solução/)
      await p.locator('#fi-goal-mode').selectOption('equal')
      await p.locator('#fi-goal-term').selectOption('11')
      assert.match(await section.locator('.fi-goal').innerText(), /6,50% a.a./)
      await p.locator('#fi-goal-term').selectOption('5')
      await section.getByRole('checkbox').check()
      await p.locator('#fi-a-tac').fill('100')
      await p.locator('#fi-b-tac').fill('150')
      assert.match(await section.locator('#fi-tac-fx-err').innerText(), /câmbio maior que zero/)
      assert.equal(await rows.nth(5).locator('.fi-cost').count(), 0, 'TAC em reais não é somada a USD sem conversão')
      assert.equal(await section.getByLabel('TAC à vista (R$)', { exact: true }).count(), 2)
      await p.locator('#fi-tac-fx').fill('5')
      assert.match(await rows.nth(5).locator('.fi-cost').first().innerText(), /4\.020,00/)
      assert.match(await rows.nth(5).locator('td').nth(2).innerText(), /^R\$\s*100,00$/)
      assert.match(await rows.nth(5).locator('td').nth(7).innerText(), /^R\$\s*150,00$/)
      await p.locator('#fi-currency').selectOption('EUR')
      assert.equal(await p.locator('#fi-a-tac').inputValue(), '100,00', 'TAC permanece em reais ao trocar a moeda')
      assert.equal(await p.locator('#fi-b-tac').inputValue(), '150,00')
      assert.equal(await p.locator('#fi-tac-fx').inputValue(), '', 'troca de moeda exige nova cotação')
      await p.locator('#fi-tac-fx').fill('6')
      assert.match(await rows.nth(5).locator('.fi-cost').first().innerText(), /4\.016,67/)
      await p.locator('#fi-currency').selectOption('BRL')
      assert.equal(await p.locator('#fi-tac-fx').count(), 0)
      assert.match(await rows.nth(5).locator('.fi-cost').first().innerText(), /^R\$\s*4\.100,00$/)
      await p.locator('#fi-currency').selectOption('USD')
      await p.locator('#fi-a-tac').fill('0')
      await p.locator('#fi-b-tac').fill('0')
      assert.equal(await section.locator('#fi-tac-fx-err').count(), 0, 'TAC zero dispensa câmbio')
      assert.match(await rows.nth(5).locator('.fi-cost').first().innerText(), /4\.000,00/)
      await section.getByRole('checkbox').uncheck()
      assert.equal(await p.locator('#fi-a-tac').count(), 0)
      assert.equal(await p.locator('[id^=fi-days-]').count(), 0, 'prazos não são campos editáveis')
      assert.deepEqual(await rows.locator('th[scope=row]').allTextContents(), Array.from({length:12}, (_,i)=>String((i+1)*30)))
      assert.equal(await section.locator('thead th[scope=colgroup]').count(), 3)
      const scroll = section.getByRole('region', {name:'Comparação por prazo'})
      const regularWidth = await section.locator('table').evaluate(table => table.getBoundingClientRect().width)
      await p.locator('#fi-principal').fill('12345678901234,56')
      await p.locator('#fi-currency').selectOption('BRL')
      await section.getByRole('checkbox').check()
      await assertWholeValues()
      assert.ok(await section.locator('table').evaluate(table => table.getBoundingClientRect().width) > regularWidth, 'colunas ampliam para quantias longas e TAC')
      assert.ok(await scroll.evaluate(region => region.scrollWidth > region.clientWidth), 'quantias longas acessíveis por rolagem')
      assert.ok((await rows.nth(5).getByRole('button').boundingBox()).height >= 44, 'quantias longas mantêm seleção acessível')
      assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'rolagem permanece dentro da região')
      await scroll.evaluate(region => { region.scrollLeft = region.scrollWidth })
      await rows.last().locator('.fi-delta').scrollIntoViewIfNeeded()
      const longLast = await rows.last().locator('.fi-delta').boundingBox(), longFrame = await scroll.boundingBox()
      assert.ok(longLast.x >= longFrame.x && longLast.x + longLast.width <= longFrame.x + longFrame.width + 1, 'última coluna acessível com quantias longas')
      await p.locator('#fi-principal').fill('100000')
      await p.locator('#fi-currency').selectOption('USD')
      await section.getByRole('checkbox').uncheck()
      await scroll.evaluate(e => {e.scrollLeft=e.scrollWidth; e.scrollTop=e.scrollHeight})
      await rows.last().locator('.fi-delta').scrollIntoViewIfNeeded()
      const visible = await rows.last().locator('.fi-delta').boundingBox(), frame = await scroll.boundingBox()
      assert.ok(visible.x >= frame.x && visible.x + visible.width <= frame.x + frame.width + 1, 'coluna final acessível')
      assert.ok(Math.abs((await rows.last().locator('th').boundingBox()).x-frame.x)<3, 'prazo permanece visível')
      await scroll.screenshot({path:`${out}/table-right-${width}.png`})
      await scroll.evaluate(e=>{e.scrollLeft=0;e.scrollTop=0})
      await scroll.focus()
      await p.keyboard.press('ArrowRight')
      await p.waitForTimeout(150)
      if(await scroll.evaluate(e=>e.scrollWidth>e.clientWidth)) assert.ok(await scroll.evaluate(e=>e.scrollLeft)>0, 'rolagem por teclado')
      await scroll.evaluate(e=>{e.scrollLeft=0;e.scrollTop=0})
      if (width === 390) {
        await scroll.scrollIntoViewIfNeeded()
        const box=await scroll.boundingBox(), cdp=await p.context().newCDPSession(p)
        const y=box.y+Math.min(box.height/2,150), x=box.x+box.width-20
        await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]})
        for(let step=1;step<=8;step++) await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x-step*24,y}]})
        await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
        await p.waitForTimeout(200)
        assert.ok(await scroll.evaluate(e=>e.scrollLeft)>0, 'rolagem com gesto de toque')
        await cdp.detach()
        await scroll.evaluate(e=>{e.scrollLeft=0;e.scrollTop=0})
      }
      await p.locator('#fi-currency').selectOption('EUR')
      assert.match(await rows.first().innerText(), /€|EUR/)
      await p.locator('#fi-principal').fill('0')
      assert.match(await p.locator('#fi-principal-err').innerText(), /principal maior que zero/)
      await p.locator('#fi-principal').fill('100000')
      await p.locator('#fi-goal-mode').selectOption('equal')
      // Cenário de precisão independente dos testes anteriores de TAC e rolagem.
      await section.getByRole('checkbox').uncheck()
      await p.locator('#fi-a-rate').fill('6')
      await p.locator('#fi-a-flat').fill('1')
      await p.locator('#fi-b-flat').fill('1')
      const difference = rows.nth(5).locator('.fi-difference strong')
      const assertTinyDifference = async sign => {
        const expected = `${sign} < 0,01 EUR`
        try {
          await p.waitForFunction(expected => document.querySelector('.fi-compare tbody tr:nth-child(6) .fi-difference strong')?.textContent.trim() === expected, expected, { timeout: 5000 })
        } catch {
          const inputs = await p.locator('#fi-principal, #fi-currency, #fi-a-rate, #fi-a-flat, #fi-b-rate, #fi-b-flat').evaluateAll(elements => Object.fromEntries(elements.map(element => [element.id, element.value])))
          assert.equal(await difference.innerText(), expected, `diferença antes de arredondar; condições ${JSON.stringify(inputs)}`)
        }
        assert.equal(await difference.innerText(), expected)
      }
      for (const [rate, sign] of [['6,0000001', '+'], ['5,9999999', '−']]) {
        await p.locator('#fi-b-rate').focus()
        await p.locator('#fi-b-rate').fill(rate)
        assert.equal(await p.locator('#fi-b-rate').inputValue(), rate)
        await assertTinyDifference(sign)
        assert.equal(await rows.nth(5).locator('.fi-difference small').count(), 0)
        assert.equal(await rows.nth(5).locator('.fi-delta').innerText(), `${sign} < 0,01 p.p.`)
        await p.locator('#fi-a-rate').focus()
        assert.equal(await p.locator('#fi-b-rate').inputValue(), '6,00')
        await assertTinyDifference(sign) // Desfocar muda a exibição, preservando o cálculo.
        await p.locator('#fi-b-rate').focus()
        assert.equal(await p.locator('#fi-b-rate').inputValue(), rate, 'foco recupera a precisão digitada')
      }
      await p.locator('#fi-b-rate').fill('8')
      await p.locator('#fi-b-flat').fill('0,5')
      assert.match(await rows.nth(5).locator('td').last().innerText(), /\+0,50 p.p./)
      assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      assert.deepEqual(errors, [])
      await p.screenshot({ path: `${out}/${width}.png`, fullPage: true })
      // Static search includes formulas, never current input values.
      await p.keyboard.press('Control+Shift+F')
      const dialog = p.getByRole('dialog', { name: 'Buscar no painel' })
      await dialog.getByRole('searchbox').fill('FINIMP')
      await dialog.getByRole('button', { name: /FINIMP/ }).first().click()
      assert.match(p.url(), /#calculadora\/finimp/)
      await section.getByRole('button', { name: 'Nova simulação' }).click()
      assert.equal(await rows.locator('button[aria-pressed=true]').count(), 0)
      assert.equal(await p.locator('#fi-principal').inputValue(), '')
      await p.close()
      console.log(`PASS FINIMP ${width}`)
    }
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exit(1) })
