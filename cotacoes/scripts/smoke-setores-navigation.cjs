const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs')
;(async()=>{
  const browser=await chromium.launch(require('./smoke-launch.cjs')()),base=process.env.SMOKE_BASE_URL||'http://127.0.0.1:8773',out=process.env.SETORES_QA_OUTPUT||'workspace-qa/setores'
  fs.mkdirSync(out,{recursive:true})
  try{for(const width of [390,820,1280]){
    const p=await browser.newPage({viewport:{width,height:1000},hasTouch:true,serviceWorkers:'block',reducedMotion:'reduce'}),errors=[]
    const now=Date.now()
    await p.clock.setFixedTime(now)
    const chooseGroup=async(section,name)=>{const select=p.getByLabel(section==='setores'?'Grupo de atendimento':'Grupo de insumos',{exact:true});if(await select.isVisible())await select.selectOption(name);else await p.getByRole('navigation',{name:section==='setores'?'Grupos editoriais':'Grupos de insumos'}).getByRole('button',{name,exact:true}).click()}
    p.on('pageerror',error=>errors.push(error.message))
    // Sector coverage now has its own versioned snapshot. No successful source
    // consultation means unavailable coverage, not a confirmed absence of news.
    const sectorFixture={schemaVersion:1,generatedAt:new Date(now).toISOString(),topics:{agricultura:{items:[]}},sourceStates:{}}
    await p.route('**/sector-news.json*',r=>r.fulfill({json:sectorFixture}))
    // Regressão: a rota raiz é estável e não pode herdar a última seleção da sessão.
    const history=[]
    const selected=async name=>{const tab=p.getByRole('tab',{name,exact:true,selected:true});try{await tab.waitFor({timeout:10000})}catch(error){fs.writeFileSync(`${out}/history-error-${width}.json`,JSON.stringify({url:p.url(),expected:name,errors,history,body:await p.locator('body').innerText()},null,2));await p.screenshot({path:`${out}/history-error-${width}.png`,fullPage:true});throw error}history.push({url:p.url(),selected:await tab.innerText(),group:await p.locator('#setores-group-select').inputValue()})}
    await p.goto(base+'/#setores')
    await selected('Indústria')
    await chooseGroup('setores','Agro e alimentos')
    await p.waitForURL('**/#setores/agricultura');await selected('Agricultura e insumos agrícolas')
    await p.reload();await selected('Agricultura e insumos agrícolas')
    await p.goBack();await p.waitForURL('**/#setores');await selected('Indústria')
    await p.reload();await selected('Indústria')
    await p.goForward();await p.waitForURL('**/#setores/agricultura');await selected('Agricultura e insumos agrícolas')
    await chooseGroup('setores','Indústria e transformação')
    await p.waitForURL('**/#setores/industria');await selected('Indústria')
    await p.goBack();await p.waitForURL('**/#setores/agricultura');await selected('Agricultura e insumos agrícolas')
    await p.goForward();await p.waitForURL('**/#setores/industria');await selected('Indústria')
    await p.reload();await selected('Indústria')
    fs.writeFileSync(`${out}/history-${width}.json`,JSON.stringify(history,null,2))
    await p.goto(base+'/#setores/veiculos-pesados')
    const sections=p.getByRole('navigation',{name:'Setores ou insumos'})
    await p.getByRole('region',{name:'Indicadores de veículos pesados'}).locator('article').first().waitFor()
    assert.match(await p.getByRole('navigation',{name:'Caminho selecionado'}).innerText(),/Indústria e transformação[\s\S]*Veículos pesados/)
    assert.equal(await p.getByRole('tab',{name:'Internet e telecom',exact:true}).count(),0,'mostra só filhos do grupo escolhido')
    await chooseGroup('setores','Tecnologia e comunicação')
    await p.getByRole('tab',{name:'Internet e telecom',exact:true}).click()
    await p.goBack();await p.waitForURL('**/#setores/veiculos-pesados')
    await p.goForward();await p.waitForURL('**/#setores/telecom')
    await chooseGroup('setores','Indústria e transformação')
    assert.match(p.url(),/#setores\/veiculos-pesados$/,'lembra tema dentro do grupo')
    await sections.getByRole('button',{name:'Insumos',exact:true}).click()
    await chooseGroup('insumos','Energia')
    assert.match(p.url(),/#setores\/petroleo$/)
    await sections.getByRole('button',{name:'Setores',exact:true}).click()
    assert.match(p.url(),/#setores\/veiculos-pesados$/,'lembra seção e assunto')
    await chooseGroup('setores','Agro e alimentos')
    await p.getByRole('tab',{name:'Agricultura e insumos agrícolas',exact:true}).click()
    const coverage=p.getByRole('region',{name:'Notícias e comunicados · últimos 5 dias'})
    await coverage.getByRole('status').filter({hasText:/^Cobertura ainda não disponível:/}).waitFor()
    assert.equal(await coverage.locator('.sector-news-list').count(),0,'não inventa publicações para cobertura indisponível')
    assert.doesNotMatch(await coverage.innerText(),/Arquivo de notícias inválido|Nenhuma manchete relevante encontrada nas fontes consultadas/)
    await coverage.getByText('Fontes consultadas e limites da cobertura',{exact:true}).click()
    assert.equal(await coverage.getByRole('link',{name:'Ministério da Agricultura e Pecuária',exact:true}).count(),1,'mantém a fonte registrada do recorte agrícola')
    assert.match(await coverage.locator('details').innerText(),/não disponível/)
    await p.screenshot({path:`${out}/bancaria-${width}.png`,fullPage:true})
    await p.getByRole('navigation',{name:'Organização dos setores'}).getByRole('button',{name:'Referência B3',exact:true}).click()
    const b3=p.getByRole('navigation',{name:'Setores econômicos da B3'})
    await b3.getByRole('button',{name:'Financeiro',exact:true}).waitFor()
    assert.equal(await b3.getByRole('button').count(),11)
    await b3.getByRole('button',{name:'Financeiro',exact:true}).click()
    assert.match(p.url(),/#setores\/b3\/financeiro$/)
    await p.getByText(/Subsetores e segmentos: ainda não incorporados/).waitFor()
    await sections.getByRole('button',{name:'Insumos',exact:true}).click()
    await sections.getByRole('button',{name:'Setores',exact:true}).click()
    assert.match(p.url(),/#setores\/b3\/financeiro$/)
    await p.screenshot({path:`${out}/b3-${width}.png`,fullPage:true})
    await p.getByRole('navigation',{name:'Organização dos setores'}).getByRole('button',{name:'Visão bancária',exact:true}).click()
    assert.match(p.url(),/#setores\/agricultura$/)
    await p.reload()
    assert.match(await p.getByRole('navigation',{name:'Caminho selecionado'}).innerText(),/Agricultura/)
    await p.keyboard.press('Control+Shift+F')
    const dialog=p.getByRole('dialog',{name:'Buscar no painel'})
    await dialog.getByRole('searchbox').fill('agricultura')
    await dialog.getByRole('button',{name:/Agricultura e insumos agrícolas/}).first().click()
    assert.match(p.url(),/#setores\/agricultura$/)
    await p.goto(base+'/#setores/cobre')
    assert.equal(await sections.getByRole('button',{name:'Insumos',exact:true}).getAttribute('aria-pressed'),'true')
    if(width===390){const select=p.getByLabel('Grupo de insumos',{exact:true});await select.focus();await p.keyboard.press('End');await p.keyboard.press('Enter')}else{await p.getByRole('navigation',{name:'Grupos de insumos'}).getByRole('button',{name:'Energia',exact:true}).focus();await p.keyboard.press('Enter')}
    assert.match(p.url(),/#setores\/petroleo$/)
    for(const button of await sections.getByRole('button').all()) assert.ok((await button.boundingBox()).height>=44)
    assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    assert.deepEqual(errors,[])
    await p.close();console.log(`PASS navegação de setores ${width}`)
  }}finally{await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)})
